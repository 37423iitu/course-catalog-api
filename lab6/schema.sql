\set ON_ERROR_STOP on
BEGIN;
CREATE TABLE courses (
    id text CONSTRAINT courses_pkey PRIMARY KEY,
    title text NOT NULL,
    description text NOT NULL DEFAULT '',
    credits smallint NOT NULL,
    is_elective boolean NOT NULL DEFAULT false,
    likes integer NOT NULL DEFAULT 0,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT courses_id_check CHECK (id ~ '^[a-z0-9]+(-[a-z0-9]+)*$'),
    CONSTRAINT courses_title_check CHECK (char_length(btrim(title)) BETWEEN 1 AND 200),
    CONSTRAINT courses_credits_check CHECK (credits BETWEEN 1 AND 10),
    CONSTRAINT courses_likes_check CHECK (likes >= 0)
);
CREATE TABLE students (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT students_pkey PRIMARY KEY,
    name text NOT NULL,
    email text NOT NULL CONSTRAINT students_email_key UNIQUE,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT students_name_check CHECK (char_length(btrim(name)) BETWEEN 2 AND 100),
    CONSTRAINT students_email_check CHECK (
        email = lower(btrim(email)) AND email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    )
);
CREATE TABLE enrollments (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT enrollments_pkey PRIMARY KEY,
    student_id bigint NOT NULL,
    course_id text NOT NULL,
    enrolled_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT enrollments_student_id_fkey FOREIGN KEY (student_id) REFERENCES students(id) ON DELETE RESTRICT,
    CONSTRAINT enrollments_course_id_fkey FOREIGN KEY (course_id) REFERENCES courses(id) ON DELETE RESTRICT,
    CONSTRAINT enrollments_student_course_key UNIQUE (student_id, course_id)
);
COMMIT;
